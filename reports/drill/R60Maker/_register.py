for iid, name, parent, used in JOBS:
    cmd = [sys.executable, '-m', 'tools.registry', 'adopt', iid,
           '--key', 'R60Maker %s %s' % (iid, name), '--name', name, '--used-by', used]
    if parent:
        cmd += ['--parent', parent]
    cmd.append('--apply')
    r = subprocess.run(cmd, capture_output=True, text=True, encoding='utf-8')
    out = (r.stdout + r.stderr).strip().splitlines()
    line = out[0] if out else '(no output)'
    if r.returncode != 0:
        fail += 1
        print('FAIL %-7s rc=%d %s' % (iid, r.returncode, line))
